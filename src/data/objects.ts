export const objectsBy = (tags: string[] = [], limit = 4) => {
  if (!tags.length) return OBJECTS.slice(0, limit);
  const scored = OBJECTS.map((o) => ({ o, s: o.tags.filter((t) => tags.includes(t)).length }))
    .sort((a, b) => b.s - a.s);
  return scored.slice(0, limit).map((x) => x.o);
};
